"""Read-only PC snapshot verification; refresh is an explicit local-map-only operation."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / 'server/parser-py'
COMMIT = '1a67d01101f52a649d5071c6997cee60c3dc7020'
FILES = [f'services/{n}.py' for n in ('parser', 'report_category', 'fine_amount_syntax', 'case_fine_supplement', 'law_values', 'law_citations', 'law_selection', 'fine_estimate', 'plate_normalize')]
FILES += ['services/data/traffic_fine_table.json']
FILES += [f'contracts/{n}.json' for n in ('parser-vectors', 'law-parser-vectors', 'explicit-fine-vectors', 'case-fine-supplement-vectors', 'raw-detail-vectors', 'report-categories')]
# These full sources are provenance only; runtime imports the extracted pure adapter.
FILES += ['services/community_capture.py', 'core/utils/raw_detail.py']

def target(path):
    if path in ('services/community_capture.py', 'core/utils/raw_detail.py'):
        return DEST / 'provenance' / path
    return DEST / path

def extracted(source):
    start = source.index('STATUS_MAP =')
    end = source.index('\n\ndef is_eligible(')
    body = source[start:end]
    # Storage dataclasses are never used by the runtime adapter.
    a = body.index('\n\nclass CaptureStoreUnavailable')
    b = body.index('\n\ndef _clean(', a)
    body = body[:a] + body[b:]
    return '"""Pure DTO portion of PC community_capture; regenerated by vendor_parser.py."""\nimport hashlib\nimport json\nimport re\nfrom datetime import date\nfrom services import fine_estimate, report_category\nfrom services.law_values import primary_law\n\n' + body + '\n'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--upstream', type=Path, default=ROOT.parent / 'pc')
    ap.add_argument('--refresh', action='store_true')
    ap.add_argument('--offline', action='store_true', help='verify pinned local snapshot only, without another checkout')
    args = ap.parse_args()
    if args.offline:
        assert not args.refresh
        for line in (DEST / 'MANIFEST.sha256').read_text().splitlines():
            if line.startswith('#'): continue
            digest, local, _upstream = line.split('  ')
            assert hashlib.sha256((DEST / local).read_bytes()).hexdigest() == digest, local
        assert (DEST / 'community_adapter.py').read_text() == extracted(target('services/community_capture.py').read_text())
        print(f'PASS: pinned local snapshot and pure DTO adapter ({COMMIT})')
        return
    lines = [f'# upstream safetyreport commit {COMMIT}', '# sha256  local_path  upstream_path']
    for path in FILES:
        data = subprocess.check_output(['git', '-C', str(args.upstream), 'show', f'{COMMIT}:{path}'])
        # Detect a dirty or newer checkout too, rather than silently comparing only git objects.
        if path != 'services/community_capture.py':
            assert (args.upstream / path).read_bytes() == data, f'upstream parser checkout differs: {path}'
        else:
            assert extracted((args.upstream / path).read_text()) == extracted(data.decode()), 'upstream DTO generation drift'
        dest = target(path)
        if args.refresh:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
        assert dest.read_bytes() == data, f'vendor drift: {path}'
        lines.append(f'{hashlib.sha256(data).hexdigest()}  {dest.relative_to(DEST)}  {path}')
    adapter = extracted(target('services/community_capture.py').read_text())
    if args.refresh:
        (DEST / 'community_adapter.py').write_text(adapter)
        (DEST / 'services/__init__.py').write_text('')
        (DEST / 'MANIFEST.sha256').write_text('\n'.join(lines) + '\n')
    assert (DEST / 'community_adapter.py').read_text() == adapter, 'pure adapter drift'
    assert (DEST / 'MANIFEST.sha256').read_text() == '\n'.join(lines) + '\n', 'manifest drift'
    print(f'PASS: {len(FILES)} source/vector files and extracted DTO match {COMMIT}')

if __name__ == '__main__':
    main()
