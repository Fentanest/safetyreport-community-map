create or replace function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger contributor_profiles_touch_updated_at
before update on private.contributor_profiles
for each row execute function private.touch_updated_at();

create or replace function public.internal_activate_snapshot(
    p_snapshot_id uuid,
    p_user_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_expected integer;
    v_received integer;
    v_payload_sha256 text;
    v_computed_sha256 text;
begin
    -- Serializes activation for one contributor.
    perform 1
      from private.contributor_profiles
     where user_id = p_user_id
       and status = 'active'
       and revoked_at is null
     for update;

    if not found then
        raise exception 'active contributor profile not found';
    end if;

    select expected_point_count, received_point_count, payload_sha256
      into v_expected, v_received, v_payload_sha256
      from private.upload_snapshots
     where id = p_snapshot_id
       and user_id = p_user_id
       and state = 'staged'
     for update;

    if not found then
        raise exception 'staged snapshot not found';
    end if;

    if v_expected <> v_received then
        raise exception 'snapshot point count mismatch';
    end if;

    -- payload_sha256 = sha256 of all chunk hashes concatenated in chunk order
    -- (docs/data-contract.md section 7).
    select encode(extensions.digest(
               coalesce(string_agg(chunk_sha256, '' order by chunk_index), ''),
               'sha256'), 'hex')
      into v_computed_sha256
      from private.upload_chunks
     where snapshot_id = p_snapshot_id;

    if v_computed_sha256 is distinct from v_payload_sha256 then
        raise exception 'snapshot payload hash mismatch';
    end if;

    update private.upload_snapshots
       set state = 'superseded',
           superseded_at = now(),
           superseded_by = p_snapshot_id
     where user_id = p_user_id
       and state = 'active';

    update private.upload_snapshots
       set state = 'active',
           finalized_at = now()
     where id = p_snapshot_id;

    update private.contributor_profiles
       set last_upload_at = now()
     where user_id = p_user_id;
end;
$$;

revoke all on function private.touch_updated_at() from public;
revoke all on function public.internal_activate_snapshot(uuid, uuid) from public;
revoke all on function public.internal_activate_snapshot(uuid, uuid) from anon;
revoke all on function public.internal_activate_snapshot(uuid, uuid) from authenticated;
grant execute on function public.internal_activate_snapshot(uuid, uuid) to service_role;

-- Retention enforcement (docs/database.md section 9). Deleting a snapshot
-- cascades to its points and chunks.
create or replace function public.internal_cleanup_expired()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    delete from private.upload_snapshots
     where state = 'staged'
       and expires_at < now();

    delete from private.upload_snapshots
     where state = 'superseded'
       and superseded_at < now() - interval '30 days';

    delete from private.upload_snapshots
     where state = 'quarantined'
       and received_at < now() - interval '7 days';

    delete from private.abuse_events
     where created_at < now() - interval '90 days';

    delete from private.rate_limits
     where window_start < now() - interval '2 days';
end;
$$;

revoke all on function public.internal_cleanup_expired() from public;
revoke all on function public.internal_cleanup_expired() from anon;
revoke all on function public.internal_cleanup_expired() from authenticated;
grant execute on function public.internal_cleanup_expired() to service_role;

