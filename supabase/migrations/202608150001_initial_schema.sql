-- Safetyreport Community Map
-- Initial Supabase schema draft.
-- Phone numbers remain in Supabase Auth. Application tables reference auth.users.id only.

create extension if not exists pgcrypto with schema extensions;

create schema if not exists private;

revoke all on schema private from public;
revoke all on schema private from anon;
revoke all on schema private from authenticated;

grant usage on schema private to service_role;

create table private.contributor_profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    consent_version text not null,
    privacy_policy_version text not null,
    consented_at timestamptz not null default now(),
    revoked_at timestamptz,
    status text not null default 'active'
        check (status in ('active', 'suspended', 'deletion_pending')),
    last_upload_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table private.upload_snapshots (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references private.contributor_profiles(user_id) on delete cascade,
    schema_version integer not null check (schema_version > 0),
    source_mode text not null
        check (source_mode in ('mobile_standalone', 'mobile_server', 'safetyreport_server')),
    state text not null default 'staged'
        check (state in ('staged', 'quarantined', 'active', 'superseded', 'deleted')),
    client_generated_at timestamptz not null,
    data_through_at timestamptz,
    expected_point_count integer not null
        check (expected_point_count between 0 and 10000),
    received_point_count integer not null default 0
        check (received_point_count between 0 and 10000),
    payload_sha256 text not null
        check (payload_sha256 ~ '^[0-9a-f]{64}$'),
    received_at timestamptz not null default now(),
    expires_at timestamptz not null default (now() + interval '1 hour'),
    finalized_at timestamptz,
    superseded_at timestamptz,
    superseded_by uuid references private.upload_snapshots(id) on delete set null,
    quarantine_reason text,
    location_key_version integer not null default 1
);

-- Partial dedupe: a payload hash blocks re-use only while it is still live.
-- A full-column unique constraint would reject a legitimate A -> B -> A
-- re-upload because of the old superseded row.
create unique index upload_snapshots_payload_dedupe
    on private.upload_snapshots(user_id, payload_sha256)
    where state in ('staged', 'active', 'quarantined');

create unique index upload_snapshots_one_active_per_user
    on private.upload_snapshots(user_id)
    where state = 'active';

create index upload_snapshots_state_received_idx
    on private.upload_snapshots(state, received_at);

create table private.upload_points (
    id bigint generated by default as identity primary key,
    snapshot_id uuid not null references private.upload_snapshots(id) on delete cascade,
    period_year smallint not null check (period_year between 2020 and 2200),
    category text not null check (category in ('traffic', 'parking', 'other')),
    location_key text not null check (location_key ~ '^[0-9a-f]{64}$'),
    lat double precision not null check (lat between 32.0 and 39.5),
    lng double precision not null check (lng between 124.0 and 132.0),
    address text not null check (char_length(address) between 1 and 200),
    region text not null default '' check (char_length(region) <= 100),
    total_count integer not null check (total_count >= 0),
    accepted_count integer not null default 0 check (accepted_count >= 0),
    processing_count integer not null default 0 check (processing_count >= 0),
    rejected_count integer not null default 0 check (rejected_count >= 0),
    withdrawn_count integer not null default 0 check (withdrawn_count >= 0),
    fine_count integer not null default 0 check (fine_count >= 0),
    status_counts jsonb not null default '{}'::jsonb
        check (jsonb_typeof(status_counts) = 'object'),
    disposition_counts jsonb not null default '{}'::jsonb
        check (jsonb_typeof(disposition_counts) = 'object'),
    agency_counts jsonb not null default '{}'::jsonb
        check (jsonb_typeof(agency_counts) = 'object'),
    manager_counts jsonb not null default '{}'::jsonb
        check (jsonb_typeof(manager_counts) = 'object'),
    created_at timestamptz not null default now(),
    check (accepted_count <= total_count),
    check (processing_count <= total_count),
    check (rejected_count <= total_count),
    check (withdrawn_count <= total_count),
    check (fine_count <= total_count),
    check (accepted_count + processing_count + rejected_count + withdrawn_count <= total_count),
    unique (snapshot_id, period_year, category, location_key)
);

create index upload_points_snapshot_idx
    on private.upload_points(snapshot_id);

create index upload_points_location_idx
    on private.upload_points(period_year, category, location_key);

create table private.upload_chunks (
    snapshot_id uuid not null references private.upload_snapshots(id) on delete cascade,
    chunk_index integer not null check (chunk_index >= 0),
    point_count integer not null check (point_count between 0 and 500),
    chunk_sha256 text not null check (chunk_sha256 ~ '^[0-9a-f]{64}$'),
    received_at timestamptz not null default now(),
    primary key (snapshot_id, chunk_index)
);

create table private.abuse_events (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete set null,
    request_id text not null,
    event_type text not null,
    severity text not null check (severity in ('info', 'warning', 'critical')),
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index abuse_events_created_idx
    on private.abuse_events(created_at);

-- Edge Functions are stateless; rate-limit counters live here.
-- Buckets that key on an IP store a hash, never the raw address.
create table private.rate_limits (
    bucket text not null,
    window_start timestamptz not null,
    request_count integer not null default 0 check (request_count >= 0),
    primary key (bucket, window_start)
);

create index rate_limits_window_idx
    on private.rate_limits(window_start);

