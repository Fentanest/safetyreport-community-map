    category text not null check (category in ('all', 'traffic', 'parking', 'other')),
    location_key text not null check (location_key ~ '^[0-9a-f]{64}$'),
    lat double precision not null check (lat between 32.0 and 39.5),
    lng double precision not null check (lng between 124.0 and 132.0),
    address text not null check (char_length(address) between 1 and 200),
    region text not null default '' check (char_length(region) <= 100),
    total_count bigint not null check (total_count >= 0),
    accepted_count bigint not null default 0 check (accepted_count >= 0),
    processing_count bigint not null default 0 check (processing_count >= 0),
    rejected_count bigint not null default 0 check (rejected_count >= 0),
    withdrawn_count bigint not null default 0 check (withdrawn_count >= 0),
    fine_count bigint not null default 0 check (fine_count >= 0),
    contributor_count integer not null check (contributor_count > 0),
    confidence text not null check (confidence in ('low', 'medium', 'high')),
    status_breakdown jsonb not null default '[]'::jsonb
        check (jsonb_typeof(status_breakdown) = 'array'),
    disposition_breakdown jsonb not null default '[]'::jsonb
        check (jsonb_typeof(disposition_breakdown) = 'array'),
    agency_breakdown jsonb not null default '[]'::jsonb
